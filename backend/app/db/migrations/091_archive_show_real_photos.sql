-- =====================================================
-- Migration 091: 藏品是否对外展示实拍照 (show_real_photos)
-- =====================================================
--
-- 详情页把 AI 三视图提为主图之后,实拍退成次要区。本人可以进一步选择
-- 「实拍不给外人看」—— 衣柜里的实拍常常带家里的环境、光线很差,
-- 用户想只用干净的白底三视图对外呈现。
--
-- 这一列只管「给别人看不看」,本人始终能看到自己的全部照片。
-- 落库的原因是它必须在服务端生效:光靠前端不渲染,实拍 URL 照样在
-- 接口响应里,任何人抓一下包就拿到了 —— 那不叫隐藏。
--
-- 默认 true:存量藏品今天的实拍就是公开的,不要在用户不知情时改变现状。
--
-- 注意一个边界:若该藏品没有任何 AI 生成图,关掉实拍会让它一张图都不剩。
-- 服务端对这种情况忽略本列(仍返回实拍),前端也不给开开关。宁可没关成,
-- 不要给出一个空白的藏品页。
-- =====================================================

ALTER TABLE user_archive_items
    ADD COLUMN IF NOT EXISTS show_real_photos BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN user_archive_items.show_real_photos IS
    'false = 他人只看到 AI 三视图,实拍不出现在接口响应里;本人不受影响。'
    '该藏品没有 AI 生成图时此列被忽略,避免出现没有任何图片的藏品页。';
